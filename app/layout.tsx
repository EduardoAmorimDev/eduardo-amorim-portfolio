import type { Metadata } from 'next'
import { Montserrat } from 'next/font/google'
import localFont from 'next/font/local'
import './globals.css'
import ReactLenis from 'lenis/react'

const montserrat = Montserrat({
  variable: '--font-montserrat',
  subsets: ['latin']
})

const warping = localFont({
  src: './fonts/warping.otf',
  variable: '--font-warping',
  weight: '400'
})

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
  icons: {
    icon: [
      { url: '/favicon_light.ico', media: '(prefers-color-scheme: light)' },
      { url: '/favicon_dark.ico', media: '(prefers-color-scheme: dark)' }
    ]
  }
}

export default function RootLayout({ children }: LayoutProps<'/'>) {
  return (
    <html
      lang="en"
      className={`${montserrat.variable} ${warping.variable} h-full antialiased`}
    >
      {/* why: anchors lets Lenis run in-page links (the hero CTA) through its
          own smooth scroll instead of the browser's jump. */}
      <ReactLenis root options={{ anchors: true }} />
      <body className="flex min-h-full flex-col">{children}</body>
    </html>
  )
}
